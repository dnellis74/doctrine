export interface TextOpts {
  size?: number;
  color?: number;
  alpha?: number;
  align?: 'left' | 'center' | 'right';
}

export function measureText(text: string, size = 3): number {
  const advance = size * 5;
  return text.length * advance;
}

export function drawText(
  g: Phaser.GameObjects.Graphics,
  text: string,
  x: number,
  y: number,
  opts: TextOpts = {},
): void {
  const size = opts.size ?? 3;
  const color = opts.color ?? 0xd9f2e6;
  const alpha = opts.alpha ?? 1;
  const align = opts.align ?? 'left';
  const upper = text.toUpperCase();
  const width = measureText(upper, size);
  let cx = x;
  if (align === 'center') cx = x - width / 2;
  else if (align === 'right') cx = x - width;

  for (const ch of upper) {
    const segs = G[ch] ?? G['.']!;
    for (const [x0, y0, x1, y1] of segs) {
      glowSeg(
        g,
        cx + x0 * size,
        y + y0 * size,
        cx + x1 * size,
        y + y1 * size,
        color,
        alpha,
      );
    }
    cx += size * 5;
  }
}

/** Word-wrap then draw centered (or left) lines. Returns bottom y. */
export function drawTextWrapped(
  g: Phaser.GameObjects.Graphics,
  text: string,
  x: number,
  y: number,
  maxWidth: number,
  opts: TextOpts = {},
): number {
  const size = opts.size ?? 3;
  const lineH = size * 8;
  const words = text.toUpperCase().split(/\s+/);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    const next = cur ? `${cur} ${w}` : w;
    if (measureText(next, size) > maxWidth && cur) {
      lines.push(cur);
      cur = w;
    } else {
      cur = next;
    }
  }
  if (cur) lines.push(cur);
  lines.forEach((line, i) => {
    drawText(g, line, x, y + i * lineH, opts);
  });
  return y + lines.length * lineH;
}
